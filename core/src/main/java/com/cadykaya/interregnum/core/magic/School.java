package com.cadykaya.interregnum.core.magic;

/**
 * The four schools, one per god.
 *
 * `WORLD.md`, locked: *"Schools, one per god, **learned in their worlds**."* The last
 * three words are the whole progression: a school is not a tech tree node you buy at
 * home, it is something you can only be taught where its god still lives — which is what
 * makes the ferry worth recommissioning and the letters worth carrying.
 *
 * Named for the law rather than for the god, because that is how a practitioner would
 * name them and because the gods already have four names each.
 */
public enum School {
    /** The Anchorite's. Lighten, Drop-forge, Loft, Moor. */
    WEIGHT,
    /** The Verdant's. Bridgeroot, Hedge, Graft, Wildgrowth. */
    VERDANCY,
    /** The Quiet One's. Hush, Still, Quell, Held-breath. */
    SILENCE,
    /** The Hearth-Turner's. Weather, Rewind, Ripen, Rot. */
    TURNING
}
